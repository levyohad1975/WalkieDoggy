#!/usr/bin/env python3
"""Build single-transaction "apply + record" SQL for a Supabase migration.

Why: the Staging migration ledger was previously written by a tool that
stamps its own version (v1.2 landed as 20261013164442 while the repository
called it 20261013070000). Applying through such a tool again would record
yet another version and keep the repository and Staging out of sync.

The generated SQL does exactly what `supabase db push` does for one file, in
one transaction: refuse if the version is already recorded or a required
predecessor is missing, run the migration body verbatim, then record the
repository version, name and statements. If any statement fails (for example
the v1.1 duplicate gate), the whole transaction rolls back and nothing --
schema or ledger -- is written.

Usage: build_ledgered_apply.py <migration.sql> [--requires VERSION ...]
Output goes to supabase/staging_apply/<same file name>.
"""
import argparse
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT_DIR = os.path.join(ROOT, 'supabase', 'staging_apply')


def build(path: str, requires: list[str]) -> str:
    file_name = os.path.basename(path)
    stem = file_name[:-4]
    version, name = stem.split('_', 1)
    body = open(path, encoding='utf-8').read()
    tag = '$ledger_body$'
    if tag in body:
        sys.exit(f'{file_name}: body contains {tag}; choose another quote tag')
    checks = ''.join(
        f"  if not exists (select 1 from supabase_migrations.schema_migrations where version = '{req}') then\n"
        f"    raise exception 'required predecessor migration {req} is not recorded; nothing applied';\n"
        f"  end if;\n"
        for req in requires
    )
    return (
        f"-- GENERATED by scripts/staging/build_ledgered_apply.py from supabase/migrations/{file_name}.\n"
        f"-- Do not edit; regenerate. src/lib/__tests__/stagingLedgeredApply.test.ts verifies the\n"
        f"-- embedded body is byte-identical to the migration file.\n"
        f"-- Applies the migration and records version {version} in ONE transaction.\n"
        f"begin;\n"
        f"do $ledger_guard$\n"
        f"begin\n"
        f"  if exists (select 1 from supabase_migrations.schema_migrations where version = '{version}') then\n"
        f"    raise exception 'migration {version} is already recorded; nothing applied';\n"
        f"  end if;\n"
        f"{checks}"
        f"end;\n"
        f"$ledger_guard$;\n"
        f"-- ===== BEGIN supabase/migrations/{file_name} =====\n"
        f"{body}"
        f"{'' if body.endswith(chr(10)) else chr(10)}"
        f"-- ===== END supabase/migrations/{file_name} =====\n"
        f"insert into supabase_migrations.schema_migrations(version, name, statements)\n"
        f"values ('{version}', '{name}', array[{tag}{body}{tag}]);\n"
        f"commit;\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('migration')
    parser.add_argument('--requires', nargs='*', default=[])
    args = parser.parse_args()
    os.makedirs(OUT_DIR, exist_ok=True)
    out = os.path.join(OUT_DIR, os.path.basename(args.migration))
    with open(out, 'w', encoding='utf-8') as handle:
        handle.write(build(args.migration, args.requires))
    print(out)


if __name__ == '__main__':
    main()
